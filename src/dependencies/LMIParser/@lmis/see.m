function see(p)
if length(p.val)==0
    disp('LMIs --------------------------------------------------------------------')
    disp(p.lmim(:))
    disp('Cost --------------------------------------------------------------------')
    disp(p.cost)
else    
    disp('Value variables ---------------------------------------------------------------')
    disp(' ')
    disp(p.var)
    disp(p.val)
    [lmv,cov]=double(p);
    disp('Value LMIs --------------------------------------------------------------------')
    disp(lmv)
    disp('Value Cost --------------------------------------------------------------------')
    disp(cov)
end
end
        